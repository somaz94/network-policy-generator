// policyKey identifies one applied policy object.
type policyKey struct {
	gvk       schema.GroupVersionKind
	namespace string
	name      string
}

func keyOf(u *unstructured.Unstructured) policyKey {
	return policyKey{gvk: u.GroupVersionKind(), namespace: u.GetNamespace(), name: u.GetName()}
}

// stampOwnership marks u as generated by g. An ownerReference only works within
// its own namespace: on a policy in another namespace the garbage collector
// treats the owner as missing and deletes the policy, so those policies are
// tracked by the UID label and removed by the finalizer instead.
func stampOwnership(u *unstructured.Unstructured, g *securityv1.NetworkPolicyGenerator) {
	labels := u.GetLabels()
	if labels == nil {
		labels = map[string]string{}
	}
	labels[policy.LabelManagedBy] = policy.ManagedByValue
	labels[policy.LabelGeneratorUID] = string(g.UID)
	u.SetLabels(labels)

	annotations := u.GetAnnotations()
	if annotations == nil {
		annotations = map[string]string{}
	}
	annotations[policy.AnnotationGenerator] = g.Namespace + "/" + g.Name
	u.SetAnnotations(annotations)

	if u.GetNamespace() == g.Namespace {
		u.SetOwnerReferences([]metav1.OwnerReference{ownerReference(g)})
	} else {
		u.SetOwnerReferences(nil)
	}
}

// managedPolicyGVKs lists every kind the generator can write, so a policy left
// behind by an earlier engine choice is still found.
func managedPolicyGVKs() []schema.GroupVersionKind {
	return []schema.GroupVersionKind{
		gvkForEngine(policy.EngineKubernetes),
		gvkForEngine(policy.EngineCilium),
		gvkForEngine(policy.EngineCalico),
	}
}

// pruneStalePolicies deletes every policy carrying g's UID label that is not in
// keep: policies for namespaces no longer listed, or of an engine no longer
// selected. Kinds whose CRD is not installed are skipped. It returns the keys
// it deleted.
func (r *NetworkPolicyGeneratorReconciler) pruneStalePolicies(
	ctx context.Context, g *securityv1.NetworkPolicyGenerator, keep map[policyKey]bool,
) ([]policyKey, error) {
	if g.UID == "" {
		return nil, nil
	}
	var deleted []policyKey
	for _, gvk := range managedPolicyGVKs() {
		list := &unstructured.UnstructuredList{}
		list.SetGroupVersionKind(gvk.GroupVersion().WithKind(gvk.Kind + "List"))
		err := r.List(ctx, list, client.MatchingLabels{policy.LabelGeneratorUID: string(g.UID)})
		if meta.IsNoMatchError(err) || apierrors.IsNotFound(err) {
			continue
		}
		if err != nil {
			return deleted, err
		}
		for i := range list.Items {
			item := &list.Items[i]
			item.SetGroupVersionKind(gvk)
			key := keyOf(item)
			if keep[key] {
				continue
			}
			if err := r.Delete(ctx, item); err != nil && !apierrors.IsNotFound(err) {
				return deleted, err
			}
			log.FromContext(ctx).Info("Deleted stale policy", "kind", gvk.Kind, "namespace", key.namespace, "name", key.name)
			deleted = append(deleted, key)
		}
	}
	return deleted, nil
}

// generatorForPolicy maps a generated policy back to the generator named in its
// annotation, so editing or deleting a policy by hand is corrected right away
// rather than at the next periodic requeue.
func generatorForPolicy(_ context.Context, obj client.Object) []reconcile.Request {
	ref := obj.GetAnnotations()[policy.AnnotationGenerator]
	ns, name, ok := strings.Cut(ref, "/")
	if !ok || ns == "" || name == "" {
		return nil
	}
	return []reconcile.Request{{NamespacedName: types.NamespacedName{Namespace: ns, Name: name}}}
}

// isManagedPolicy reports whether obj was written by this controller.
func isManagedPolicy(obj client.Object) bool {
	return obj.GetLabels()[policy.LabelManagedBy] == policy.ManagedByValue
}
